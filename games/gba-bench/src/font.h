// 字 → タイルの番号（無い字は空白）
static inline unsigned short font_tile(char c) {
    if (c >= '0' && c <= '9') return (unsigned short) (1 + c - '0');
    if (c >= 'A' && c <= 'Z') return (unsigned short) (11 + c - 'A');
    switch (c) {
    case '-': return 37;
    case '/': return 38;
    case ':': return 39;
    case '.': return 40;
    default: return 0;
    }
}
